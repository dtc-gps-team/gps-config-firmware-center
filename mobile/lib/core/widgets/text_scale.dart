import 'package:flutter/widgets.dart';

/// ผู้ใช้ตั้งตัวอักษรระบบใหญ่ตั้งแต่ 1.3 เท่าขึ้นไป (Android ตั้งได้ถึง 2 เท่า)
///
/// ใช้สลับ layout แบบ "ข้อความ + ป้ายด้านข้าง" ในแถวเดียว เป็นแบบเรียงลงล่าง
/// เพราะตอนตัวอักษรใหญ่ ป้ายด้านข้างกินความกว้างจนข้อความหลักเหลือที่นิดเดียว
/// (ชื่องานถูกตัด เลขเครื่องขึ้นบรรทัดใหม่ทีละตัวอักษร) หรือล้นขอบจอ
/// (UX audit #9, #23) · ตัวอักษรปกติ layout เดิมไม่เปลี่ยน
bool isLargeTextScale(BuildContext context) =>
    MediaQuery.textScalerOf(context).scale(10) >= 13;
